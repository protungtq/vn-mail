/**
 * The words of the interface, in English and Vietnamese.
 *
 * Components read them through `useT()` (src/lib/useT.ts), which re-renders
 * them when the language changes. Code outside components (the store, the
 * date helpers, the phishing checks) uses `t()` here, which reads the
 * language the store last set with `setCurrentLanguage` — the same
 * module-level mirror the 12-hour clock uses in dates.ts.
 *
 * Keys are flat dot-notation, grouped by area. A value may hold
 * `{name}` placeholders, filled from the `vars` argument. When `vars`
 * holds `count`, the `.one` form is used for 1 and the `.other` form
 * otherwise, so English plurals and Vietnamese (which does not inflect)
 * share one call shape. A missing key falls back to English, then to
 * the key itself, so a gap never breaks the window.
 */

export type Language = "en" | "vi";

/** The language a settings record asks for; anything else means English. */
export function langOf(settings: Record<string, string>): Language {
  return settings.language === "vi" ? "vi" : "en";
}

