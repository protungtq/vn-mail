function fill(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

/** The words for `key` in `lang`, with `{placeholders}` filled. Falls back to English, then to the key. */
export function translate(lang: Language, key: string, vars?: Vars): string {
  const count = vars?.count;
  const keys = typeof count === "number" ? [`${key}.${count === 1 ? "one" : "other"}`, key] : [key];
  for (const candidate of keys) {
    const found = dictionaries[lang][candidate] ?? dictionaries.en[candidate];
    if (found !== undefined) return fill(found, vars);
  }
  return key;
}

/** The language in force for code outside components. The store keeps it in step with the setting. */
let current: Language = "en";

/** Set the language `t()` reads. Called by the store when preferences load and when the setting changes. */
export function setCurrentLanguage(lang: Language) {
  current = lang;
}

export function getLanguage(): Language {
  return current;
}

/** `translate` in the language currently in force. Components prefer `useT()`, which also re-renders them. */
export function t(key: string, vars?: Vars): string {
  return translate(current, key, vars);
}
